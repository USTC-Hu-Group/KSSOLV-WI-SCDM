function export_si_results(include_wlmf)
% Compact, case-local plotting data; eigenvalues are relative to the same DFT E_F.
case_dir = si_case_setup;
s = load(fullfile(case_dir, 'band_compare_checkpoint.mat'));
n = load(fullfile(case_dir, 'nscf_checkpoint.mat'), 'crystal', 'metadata');
p = load(fullfile(case_dir, 'nscf_path_checkpoint.mat'), ...
    'k_path_fractional', 'path_distance_bohr_inv', 'energyBands');
methods = {'wi-scdm'; 'wi-scdm-f'};
bands = {s.bands_scdm; s.bands_scdm_f};
details = {s.band_error_detail; s.band_error_detail_f};
if include_wlmf
    w = load(fullfile(case_dir, 'wlmf_checkpoint.mat'), 'result');
    c = w.result.band_compare;
    reference = (p.energyBands(1:size(c.bands_w90, 2), :).' - ...
        n.crystal.efermi)*27.211386246;
    assert(isequal(size(reference), size(c.energy_ref)) && ...
        max(abs(reference(:)-c.energy_ref(:))) < 1e-7, ...
        'si:ForeignDFTReference', ...
        'MLWF reference energies differ from this case DFT data.');
    assert(isequal(size(c.k_path), size(p.k_path_fractional)) && ...
        max(abs(c.k_path(:)-p.k_path_fractional(:))) < 1e-12, ...
        'si:ForeignKPath', ...
        'MLWF k path differs from this case DFT path.');
    methods{end+1, 1} = 'wlmf';
    bands{end+1, 1} = c.bands_w90;
    details{end+1, 1} = c.band_error_detail;
end
rows = zeros(numel(methods), 7);
for i = 1:numel(methods)
    d = details{i};
    rows(i, :) = [d.mae, d.rmse, d.max_absolute_error, d.eta, ...
        d.eta_max, d.nkpts, d.nbnd];
    [nk, nb] = size(bands{i});
    reference = (p.energyBands(1:nb, :).' - n.crystal.efermi)*27.211386246;
    [kindex, bindex] = ndgrid(1:nk, 1:nb);
    values = [kindex(:), bindex(:), ...
        repmat(p.k_path_fractional, nb, 1), ...
        repmat(p.path_distance_bohr_inv, nb, 1), reference(:), ...
        bands{i}(:), bands{i}(:)-reference(:)];
    data = array2table(values, 'VariableNames', {'k_index','band_index', ...
        'k1_frac','k2_frac','k3_frac','distance_bohr_inv', ...
        'DFT_eV','interpolated_eV','difference_eV'});
    writetable(data, fullfile(case_dir, 'results', ...
        [strrep(methods{i}, '-', '_') '_bands.csv']));
end
summary = [table(string(methods), 'VariableNames', {'method'}), ...
    array2table(rows, 'VariableNames', {'MAE_eV','RMSE_eV','MAX_eV', ...
    'eta_eV','eta_max_eV','compared_kpoints','n_wannier'})];
summary.system = repmat(string(n.metadata.system_name), height(summary), 1);
summary.nscf_nkpts = repmat(n.crystal.nkpts, height(summary), 1);
summary.nscf_nbnd = repmat(n.crystal.nbnd, height(summary), 1);
writetable(summary, fullfile(case_dir, 'results', 'si_error_summary.csv'));
end
