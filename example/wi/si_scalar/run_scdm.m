function run_scdm
% Step 3. One automatic SCDM basis, two Hamiltonian interpolation methods.
case_dir = si_case_setup;
diary(fullfile(case_dir, 'logs', 'run_scdm.log'));
cleanup = onCleanup(@() diary('off'));
s = load(fullfile(case_dir, 'nscf_checkpoint.mat'), 'crystal', 'info', 'metadata');
p = load(fullfile(case_dir, 'nscf_path_checkpoint.mat'), ...
    'energyBands', 'k_path_fractional', 'path_distance_bohr_inv');
crystal = s.crystal;
metadata = s.metadata;
energyBands = p.energyBands;
write_input_files(crystal, s.info.Eigvals, [], metadata.focc);
[wan_r, Amn, cube_files] = scdm_m('scdm.in', 'scdm.amn');
save(fullfile(case_dir, 'scdm_checkpoint.mat'), ...
    'wan_r', 'Amn', 'cube_files', 'metadata', '-v7.3');
[bands_scdm, H_R, transform_info] = compare_scdm_bands( ...
    metadata.path_kpoints, energyBands, crystal, 'scdm.amn', 'Method', 'wi-scdm');
[err_aver, err_max, err_rms, band_error_detail] = calculate_err( ...
    bands_scdm, energyBands, crystal, 'Method', 'wi-scdm', ...
    'BandErrorMode', metadata.band_error_mode, 'Nu', metadata.nu, 'Tau', metadata.tau);
[bands_scdm_f, H_R_f, transform_info_f] = compare_scdm_bands( ...
    metadata.path_kpoints, energyBands, crystal, 'scdm.amn', 'Method', 'wi-scdm-f');
[err_aver_f, err_max_f, err_rms_f, band_error_detail_f] = calculate_err( ...
    bands_scdm_f, energyBands, crystal, 'Method', 'wi-scdm-f', ...
    'BandErrorMode', metadata.band_error_mode, 'Nu', metadata.nu, 'Tau', metadata.tau);
save(fullfile(case_dir, 'band_compare_checkpoint.mat'), ...
    'bands_scdm', 'H_R', 'bands_scdm_f', 'H_R_f', 'energyBands', ...
    'err_aver', 'err_max', 'err_rms', 'band_error_detail', ...
    'err_aver_f', 'err_max_f', 'err_rms_f', 'band_error_detail_f', ...
    'transform_info', 'transform_info_f', 'metadata', '-v7.3');
for method = {'wi-scdm', 'wi-scdm-f'}
    assert(has_vitale_band_error(fullfile(case_dir, 'err.txt'), ...
        method{1}, metadata.band_error_mode, metadata.nu, metadata.tau), ...
        'Missing current eta/eta_max for %s.', method{1});
end
% Both interpolations reuse this basis. Do not label it a distinct SCDM-f spread.
[spread_table, spread_summary] = calculate_scdm_spread( ...
    'CubePattern', fullfile(case_dir, 'scdm_*.cube'), ...
    'OutputPrefix', fullfile(case_dir, 'results', 'si_scdm_spread'));
save(fullfile(case_dir, 'spread_checkpoint.mat'), ...
    'spread_table', 'spread_summary', 'metadata', '-v7.3');
export_si_results(false);
fprintf('=== Si SCDM complete (automatic num_wann, mu, sigma) ===\n');
end
