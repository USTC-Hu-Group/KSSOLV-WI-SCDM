function result = run_wlmf
% Step 4. Call the shared WI/run_wannier90.m; do not shadow it with a wrapper.
case_dir = si_case_setup;
diary(fullfile(case_dir, 'logs', 'run_wlmf.log'));
cleanup = onCleanup(@() diary('off'));
s = load(fullfile(case_dir, 'nscf_checkpoint.mat'), 'metadata');
metadata = s.metadata;
assert(isfile(fullfile(case_dir, 'nscf_path_checkpoint.mat')), ...
    'Run run_nscf first: the independent DFT path checkpoint is required.');
conv_tol = env_number('W90_CONV_TOL', [], true);
command = getenv('W90_COMMAND');
if isempty(strtrim(command)), command = 'wannier90.x'; end
result = run_wannier90('WorkingDirectory', case_dir, ...
    'SeedName', 'wannier90', 'OutputDirectory', 'wannier90_post', ...
    'W90Command', command, 'NumIter', env_number('W90_NUM_ITER', 10000), ...
    'DisNumIter', env_number('W90_DIS_NUM_ITER', 0), ...
    'ConvTol', conv_tol, 'ConvWindow', env_number('W90_CONV_WINDOW', 3), ...
    'KmeshTol', 1e-8, 'Force', true, 'ErrorOnFailure', true);
assert(result.status == 0, 'Wannier90 failed; inspect wannier90_post logs.');
result.band_compare = compare_w90_bands('WorkingDirectory', case_dir, ...
    'SeedName', 'wannier90', 'W90Directory', 'wannier90_post', ...
    'Method', 'wlmf', 'BandErrorMode', metadata.band_error_mode, ...
    'Nu', metadata.nu, 'Tau', metadata.tau, ...
    'RecomputeReferenceIfMissing', false, ...
    'OutputPrefix', fullfile(case_dir, 'results', 'compare_wannier90_bands'));
save(fullfile(case_dir, 'wlmf_checkpoint.mat'), 'result', 'metadata', '-v7.3');
assert(has_vitale_band_error(fullfile(case_dir, 'err.txt'), 'wlmf', ...
    metadata.band_error_mode, metadata.nu, metadata.tau), ...
    'Missing current MLWF eta/eta_max. Check the active release src path.');
export_si_results(true);
fprintf('=== Si MLWF complete; all three methods exported ===\n');
end

function value = env_number(name, default_value, allow_auto)
if nargin < 3, allow_auto = false; end
text = strtrim(getenv(name));
if isempty(text) || (allow_auto && strcmpi(text, 'auto'))
    value = default_value;
    return;
end
value = str2double(text);
assert(isscalar(value) && isfinite(value) && value >= 0, ...
    'Invalid numeric environment setting %s=%s.', name, text);
end
