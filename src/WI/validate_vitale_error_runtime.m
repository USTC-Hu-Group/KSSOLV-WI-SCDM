function validate_vitale_error_runtime
%VALIDATE_VITALE_ERROR_RUNTIME Check the shared metric installation before SCF.
% Print actual resolved paths so cluster logs expose shadowed old functions.
wi_root = fileparts(mfilename('fullpath'));
names = {'calculate_band_error', 'calculate_err', 'compare_w90_bands', ...
    'has_vitale_band_error', 'run_wannier90', 'write_w90_mmn'};
for i = 1:numel(names)
    resolved = which(names{i});
    fprintf('WI runtime: %s -> %s\n', names{i}, resolved);
    if ~strcmpi(strrep(fileparts(resolved), '\', '/'), ...
            strrep(wi_root, '\', '/'))
        error('validate_vitale_error_runtime:ShadowedFunction', ...
            ['%s must resolve from %s, but resolves to %s. ', ...
             'Update WI_ROOT and remove stale case-local function copies.'], ...
            names{i}, wi_root, resolved);
    end
end

% Analytic FD occupations distinguish Eq. (26) from an unweighted maximum.
a = log(3);
w = [sqrt(1/8); sqrt(3)/4];
[eta, detail] = calculate_band_error([0; -a], [a; a], ...
    'entangled', 'Nu', 0, 'Tau', 1);
expected_eta = a * sqrt((w(1) + 4*w(2)) / sum(w));
if ~isfield(detail, 'metric_definition') || ...
        ~strcmp(detail.metric_definition, 'vitale2020-v1') || ...
        ~isfield(detail, 'eta_max') || ...
        ~isfinite(eta) || ~isfinite(detail.eta_max) || ...
        abs(eta - expected_eta) > 1e-12 || ...
        abs(detail.eta_max - 2*a*w(2)) > 1e-12
    error('validate_vitale_error_runtime:WrongMetricVersion', ...
        'Update the shared WI functions: Vitale eta/eta_max self-check failed.');
end
fprintf('WI runtime: vitale2020-v1 eta/eta_max self-check passed.\n');
end
